def normalize_character(data):
    raw = data.get("character", data.get("persona", "kola"))
    if not isinstance(raw, str):
        return None
    return CHARACTER_ALIASES.get(raw.strip().lower())


def load_recent_ids(filename):
    path = BASE_DIR / filename
    with file_lock:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            ids = data.get("recent_ids", [])
            if isinstance(ids, list):
                return [str(x) for x in ids if isinstance(x, str)]
        except (OSError, ValueError, TypeError):
            pass
    return []


def save_recent_ids(filename, ids):
    path = BASE_DIR / filename
    with file_lock:
        path.write_text(
            json.dumps({"recent_ids": ids[-30:]}, ensure_ascii=False, indent=2),
            encoding="utf-8"
        )


def choose_scenario(character):
    config = CHARACTERS[character]
    scenarios = config["scenarios"]
    if not scenarios:
        return None

    filename = config["recent_file"]
    recent = load_recent_ids(filename)
    available = [item for item in scenarios if item["id"] not in recent]

    if not available:
        available = scenarios[:]
        recent = []

    scenario = random.choice(available)
    recent.append(scenario["id"])
    save_recent_ids(filename, recent)
    return scenario


def get_session_key(data, character):
    chat_id = data.get("chat_id")
    if isinstance(chat_id, str) and chat_id.strip():
        return f"{character}:chat:{chat_id.strip()[:120]}"

    # Временная совместимость со старым Android-клиентом.
    # Для надёжной изоляции нескольких чатов Android должен передавать chat_id.
    remote = request.headers.get("X-Forwarded-For", request.remote_addr or "unknown")
    return f"{character}:device:{remote.split(',')[0].strip()}"


def clean_conversation(incoming, message):
    conversation = []
    if isinstance(incoming, list):
        for item in incoming[-20:]:
            if not isinstance(item, dict):
                continue
            role = item.get("role")
            content = item.get("content")
            if role not in ("user", "assistant"):
                continue
            if not isinstance(content, str) or not content.strip():
                continue
            conversation.append({
                "role": role,
                "content": content.strip()[:4000]
            })

    if (
        not conversation
        or conversation[-1]["role"] != "user"
        or conversation[-1]["content"] != message
    ):
        conversation.append({"role": "user", "content": message})

    return conversation


